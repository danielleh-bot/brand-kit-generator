/**
 * Normalise a language tag like "de-DE", "en_US", "EN", "German (de-DE)" to
 * its 2-letter ISO base. Returns null if no recognisable code is found.
 */
function normaliseLang(lang) {
  if (!lang || typeof lang !== 'string') return null;
  const m = lang.toLowerCase().match(/\b([a-z]{2})\b/);
  return m ? m[1] : null;
}

/**
 * Look up the localized strings table for a given language tag, falling back
 * to English if the language isn't in the table.
 */
function getStrings(lang) {
  const code = normaliseLang(lang);
  return (code && STRINGS[code]) || STRINGS.en;
}

/**
 * Look up a single localized label by key + language. Returns the English
 * value if either the language or the key is unknown.
 */
function t(key, lang) {
  const strings = getStrings(lang);
  return strings[key] || STRINGS.en[key] || key;
}

module.exports = { STRINGS, normaliseLang, getStrings, t };
